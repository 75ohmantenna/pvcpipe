package org.schabi.newpipe.extractor.services.kick;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.exceptions.ParsingException;
import org.schabi.newpipe.extractor.stream.AudioStream;
import org.schabi.newpipe.extractor.stream.DeliveryMethod;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;
import org.schabi.newpipe.extractor.stream.VideoStream;

import java.util.List;
import java.util.Locale;

@Tag("offline")
class KickHlsTest {
    private static final String MASTER = "https://cdn.example/path/master.m3u8?token=master%2B";
    private static final String VIDEO = "#EXT-X-STREAM-INF:BANDWIDTH=3000000,"
            + "AVERAGE-BANDWIDTH=2400000,RESOLUTION=1280x720";
    private static final String GROUPS = "#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID=\"audio\","
            + "NAME=\"Original, stereo\",LANGUAGE=\"fr\",URI=\"audio.m3u8?sig=a%2Bb,c\"\n"
            + "#EXT-X-MEDIA:TYPE=SUBTITLES,GROUP-ID=\"text\",NAME=\"English, captions\","
            + "LANGUAGE=\"en\",URI=\"../en.m3u8?sig=c%2Bd\"\n"
            + "#EXT-X-MEDIA:TYPE=SUBTITLES,GROUP-ID=\"text\",NAME=\"French\","
            + "LANGUAGE=\"fr-FR\",URI=\"fr.m3u8\"\n";

    @Test
    void quotedGroupsAndSignedUrlsKeepTheirMeaning() throws Exception {
        final KickHls.Manifest parsed = KickHls.parse(MASTER, ("#EXTM3U\n" + GROUPS + VIDEO
                + ",CODECS=\"avc1.4d401f,mp4a.40.2\",AUDIO=\"audio\",SUBTITLES=\"text\"\n"
                + "# a comment between the attributes and URL\n"
                + "720.m3u8?sig=x%2By&key=keep%2Fcase\n").replace("\n", "\r\n"));
        assertTrue(parsed.getVideoStreams().isEmpty());
        assertEquals(1, parsed.getVideoOnlyStreams().size());
        final VideoStream video = parsed.getVideoOnlyStreams().get(0);
        assertTrue(video.isVideoOnly());
        assertEquals("720p", video.getResolution());
        assertEquals("https://cdn.example/path/720.m3u8?sig=x%2By&key=keep%2Fcase",
                video.getContent());
        assertEquals(video.getContent(), video.getManifestUrl());
        assertEquals(2400000, video.getBitrate());
        final AudioStream audio = parsed.getAudioStreams().get(0);
        assertEquals("https://cdn.example/path/audio.m3u8?sig=a%2Bb,c", audio.getContent());
        assertEquals(MASTER, audio.getManifestUrl());
        assertEquals(DeliveryMethod.HLS, audio.getDeliveryMethod());
        assertEquals(MediaFormat.M4A, audio.getFormat());
        assertEquals(AudioStream.UNKNOWN_BITRATE, audio.getAverageBitrate());
        assertEquals("Original, stereo", audio.getAudioTrackName());
        assertEquals(Locale.FRENCH, audio.getAudioLocale());
        assertEquals(audio.getId(), audio.getAudioTrackId());
        assertEquals(List.of("en", "fr-FR"), parsed.getSubtitles().stream()
                .map(SubtitlesStream::getLanguageTag).toList());
        final SubtitlesStream text = parsed.getSubtitles().get(0);
        assertEquals("https://cdn.example/en.m3u8?sig=c%2Bd", text.getContent());
        assertEquals(MASTER, text.getManifestUrl());
        assertEquals(DeliveryMethod.HLS, text.getDeliveryMethod());
        assertEquals(MediaFormat.VTT, text.getFormat());
        assertFalse(text.isAutoGenerated());
    }

    @Test
    void ordinaryAndHighFrameRatesCoexistAndOnlyExactDuplicatesDisappear() throws Exception {
        final String normal = VIDEO + ",FRAME-RATE=30\n720.m3u8?sig=normal\n";
        final String fast = VIDEO + ",FRAME-RATE=59.94\n720.m3u8?sig=fast\n";
        final String differentCodec = VIDEO + ",FRAME-RATE=59.94,CODECS=\"hvc1.1.6.L93\"\n"
                + "720.m3u8?sig=fast\n";
        final KickHls.Manifest parsed = KickHls.parse(MASTER,
                "#EXTM3U\n" + normal + fast + fast + differentCodec);
        assertEquals(List.of("720p", "720p60", "720p60"), parsed.getVideoStreams().stream()
                .map(VideoStream::getResolution).toList());
        assertFalse(parsed.getVideoStreams().get(0).isVideoOnly());
        assertTrue(parsed.getVideoOnlyStreams().isEmpty());
    }

    @Test
    void uriLessAudioIsMuxedButNeverAnIndependentAudioDownload() throws Exception {
        final KickHls.Manifest parsed = KickHls.parse(MASTER, "#EXTM3U\n"
                + "#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID=\"a\",NAME=\"Muxed\",LANGUAGE=\"en\"\n"
                + "#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID=\"a\",NAME=\"French\","
                + "LANGUAGE=\"fr\",URI=\"audio.m3u8\"\n"
                + VIDEO + ",AUDIO=\"a\"\nvideo.m3u8\n");
        assertEquals(1, parsed.getVideoStreams().size());
        assertFalse(parsed.getVideoStreams().get(0).isVideoOnly());
        assertTrue(parsed.getVideoOnlyStreams().isEmpty());
        assertEquals(1, parsed.getAudioStreams().size());
        assertEquals("French", parsed.getAudioStreams().get(0).getAudioTrackName());
    }

    @Test
    void groupsAreScopedAndStableAcrossVariantOrderAndDuplicateDeclarations() throws Exception {
        final String media = "#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID=\"a\",NAME=\"Original\","
                + "LANGUAGE=\"en\",URI=\"a.m3u8\",BANDWIDTH=128000\n";
        final String unused = "#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID=\"unused\",NAME=\"Other\","
                + "URI=\"unused.m3u8\"\n";
        final String first = VIDEO + ",AUDIO=\"a\"\nvideo.m3u8\n";
        final String second = VIDEO + ",FRAME-RATE=60,AUDIO=\"a\"\nfast.m3u8\n";
        final KickHls.Manifest parsed = KickHls.parse(MASTER,
                "#EXTM3U\n" + media + media + unused + first + second);
        final KickHls.Manifest reordered = KickHls.parse(MASTER,
                "#EXTM3U\n" + media + second + first);
        assertEquals(1, parsed.getAudioStreams().size());
        assertEquals(128, parsed.getAudioStreams().get(0).getAverageBitrate());
        assertEquals(parsed.getAudioStreams().get(0).getAudioTrackId(),
                reordered.getAudioStreams().get(0).getAudioTrackId());
        assertEquals(2, parsed.getVideoOnlyStreams().size());
    }

    @Test
    void sameNamedTracksInDifferentGroupsRemainDistinct() throws Exception {
        final String a = "#EXT-X-MEDIA:TYPE=SUBTITLES,GROUP-ID=\"a\",NAME=\"Captions\","
                + "LANGUAGE=\"en\",URI=\"a.m3u8\"\n";
        final String b = a.replace("GROUP-ID=\"a\"", "GROUP-ID=\"b\"")
                .replace("URI=\"a.m3u8\"", "URI=\"b.m3u8\"");
        final KickHls.Manifest parsed = KickHls.parse(MASTER, "#EXTM3U\n" + a + b
                + VIDEO + ",SUBTITLES=\"a\"\none.m3u8\n"
                + VIDEO + ",SUBTITLES=\"b\"\ntwo.m3u8\n");
        assertEquals(2, parsed.getSubtitles().size());
        assertNotEquals(parsed.getSubtitles().get(0).getId(), parsed.getSubtitles().get(1).getId());
    }

    @Test
    void audioOnlyVariantsNeedPositiveCodecEvidenceAndUseTheirOwnBitrate() throws Exception {
        final KickHls.Manifest parsed = KickHls.parse(MASTER, "#EXTM3U\n"
                + "#EXT-X-STREAM-INF:BANDWIDTH=160000,AVERAGE-BANDWIDTH=128000,"
                + "CODECS=\"mp4a.40.2\"\naudio.m3u8?sig=keep\n");
        assertTrue(parsed.getVideoStreams().isEmpty());
        assertTrue(parsed.getVideoOnlyStreams().isEmpty());
        assertEquals(1, parsed.getAudioStreams().size());
        assertEquals(128, parsed.getAudioStreams().get(0).getAverageBitrate());
        assertNull(parsed.getAudioStreams().get(0).getAudioLocale());
        assertEquals(MASTER, parsed.getAudioStreams().get(0).getManifestUrl());
        assertEquals("https://cdn.example/path/audio.m3u8?sig=keep",
                parsed.getAudioStreams().get(0).getContent());
    }

    @ParameterizedTest
    @ValueSource(strings = {"", ",CODECS=\"mystery\"", ",CODECS=\"avc1.4d401f,mp4a.40.2\"",
            ",CODECS=\"mp4a.40.2,unknown\""})
    void unknownOrVideoCodecsWithoutResolutionDoNotInventAudio(final String codec) {
        assertThrows(ParsingException.class, () -> KickHls.parse(MASTER,
                "#EXTM3U\n#EXT-X-STREAM-INF:BANDWIDTH=128000" + codec + "\nmedia.m3u8\n"));
    }

    @Test
    void missingOrInvalidLanguagesAreNotInvented() throws Exception {
        final KickHls.Manifest parsed = KickHls.parse(MASTER, "#EXTM3U\n"
                + "#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID=\"a\",NAME=\"Unknown\","
                + "LANGUAGE=\"invalid language\",URI=\"a.m3u8\"\n"
                + "#EXT-X-MEDIA:TYPE=SUBTITLES,GROUP-ID=\"s\",NAME=\"Unknown\","
                + "URI=\"s.m3u8\"\n"
                + "#EXT-X-MEDIA:TYPE=SUBTITLES,GROUP-ID=\"s\",NAME=\"Invalid\","
                + "LANGUAGE=\"und\",URI=\"invalid.m3u8\"\n"
                + VIDEO + ",AUDIO=\"a\",SUBTITLES=\"s\"\nvideo.m3u8\n");
        assertNull(parsed.getAudioStreams().get(0).getAudioLocale());
        assertEquals(AudioStream.UNKNOWN_BITRATE, parsed.getAudioStreams().get(0)
                .getAverageBitrate());
        assertTrue(parsed.getSubtitles().isEmpty());
    }

    @Test
    void directMediaPlaylistKeepsUnknownCombinedFallbackAndImmutableLists() throws Exception {
        final KickHls.Manifest parsed = KickHls.parse(MASTER,
                "#EXTM3U\n#EXT-X-TARGETDURATION:2\n#EXTINF:2,\nsegment.ts\n#EXT-X-ENDLIST\n");
        assertEquals(1, parsed.getVideoStreams().size());
        final VideoStream video = parsed.getVideoStreams().get(0);
        assertEquals(MASTER, video.getContent());
        assertEquals(MASTER, video.getManifestUrl());
        assertEquals("unknown", video.getResolution());
        assertFalse(video.isVideoOnly());
        assertThrows(UnsupportedOperationException.class, () -> parsed.getVideoStreams().clear());
        assertThrows(UnsupportedOperationException.class,
                () -> parsed.getVideoOnlyStreams().add(video));
        assertThrows(UnsupportedOperationException.class,
                () -> parsed.getAudioStreams().add(null));
        assertThrows(UnsupportedOperationException.class, () -> parsed.getSubtitles().add(null));
    }

    @Test
    void signedAbsoluteUrlsAreNotNormalized() throws Exception {
        final String signed = "https://cdn.example/a/../b.m3u8?sig=A%2fb%2BC&name=a,b";
        final KickHls.Manifest parsed = KickHls.parse(MASTER,
                "#EXTM3U\n" + VIDEO + "\n" + signed + "\n");
        assertEquals(signed, parsed.getVideoStreams().get(0).getContent());
    }

    @ParameterizedTest
    @ValueSource(strings = {"BANDWIDTH=0", "BANDWIDTH=-1", "BANDWIDTH=NaN",
            "BANDWIDTH=2147483648", "BANDWIDTH=1,AVERAGE-BANDWIDTH=Infinity",
            "BANDWIDTH=1,AVERAGE-BANDWIDTH=2147483648", "BANDWIDTH=1,FRAME-RATE=NaN",
            "BANDWIDTH=1,FRAME-RATE=Infinity", "BANDWIDTH=1,FRAME-RATE=2147483648",
            "BANDWIDTH=1,FRAME-RATE=0", "BANDWIDTH=1,FRAME-RATE=-1",
            "BANDWIDTH=1,FRAME-RATE=1e309", "BANDWIDTH=1,RESOLUTION=1x0",
            "BANDWIDTH=1,RESOLUTION=2147483648x720", "BANDWIDTH=1,RESOLUTION=1x2147483648",
            "BANDWIDTH=1,RESOLUTION=NaNx720", "RESOLUTION=1280x720"})
    void malformedNumericMetadataFails(final String attributes) {
        assertThrows(ParsingException.class, () -> KickHls.parse(MASTER,
                "#EXTM3U\n#EXT-X-STREAM-INF:" + attributes + "\nmedia.m3u8\n"));
    }

    @ParameterizedTest
    @ValueSource(strings = {"http://cdn.example/media.m3u8", "ftp://cdn.example/media.m3u8",
            "https://user@cdn.example/media.m3u8", "https://cdn.example/bad path.m3u8"})
    void unsafeVideoAudioAndSubtitleUrlsFail(final String url) {
        assertThrows(ParsingException.class, () -> KickHls.parse(MASTER,
                "#EXTM3U\n" + VIDEO + "\n" + url + "\n"));
        for (final String type : List.of("AUDIO", "SUBTITLES")) {
            assertThrows(ParsingException.class, () -> KickHls.parse(MASTER, "#EXTM3U\n"
                    + "#EXT-X-MEDIA:TYPE=" + type + ",GROUP-ID=\"g\",NAME=\"Track\","
                    + "LANGUAGE=\"fr\",URI=\"" + url + "\"\n"
                    + VIDEO + "," + type + "=\"g\"\nvideo.m3u8\n"));
        }
    }

    @ParameterizedTest
    @ValueSource(strings = {"#EXTM3U\n", "not a playlist", "#EXTM3U\n#EXT-X-STREAM-INF:"
            + "BANDWIDTH=1,RESOLUTION=1x1\n#comment\n", "#EXTM3U\n#EXT-X-STREAM-INF:"
            + "BANDWIDTH=1,RESOLUTION=1x1,CODECS=\"unterminated\nvideo.m3u8\n",
            "#EXTM3U\n#EXT-X-STREAM-INF:BANDWIDTH=1,BANDWIDTH=2,RESOLUTION=1x1\nv.m3u8\n"})
    void malformedPlaylistsFailInsteadOfReturningFakeStreams(final String manifest) {
        assertThrows(ParsingException.class, () -> KickHls.parse(MASTER, manifest));
    }
}
