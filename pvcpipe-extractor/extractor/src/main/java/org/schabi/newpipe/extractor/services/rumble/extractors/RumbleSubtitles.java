package org.schabi.newpipe.extractor.services.rumble.extractors;

import com.grack.nanojson.JsonArray;
import com.grack.nanojson.JsonObject;

import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.exceptions.ParsingException;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

import javax.annotation.Nullable;

import static org.schabi.newpipe.extractor.utils.Utils.isNullOrEmpty;

final class RumbleSubtitles {
    private RumbleSubtitles() {
    }

    static List<SubtitlesStream> extract(@Nullable final JsonObject embed,
                                        @Nullable final JsonObject details) {
        final List<SubtitlesStream> tracks = new ArrayList<>();
        final Object embedCaptions = embed == null ? null : embed.get("cc");
        if (embedCaptions instanceof JsonObject) {
            final JsonObject captions = (JsonObject) embedCaptions;
            for (final String code : captions.keySet()) {
                final Object caption = captions.get(code);
                if (caption instanceof JsonObject) {
                    add(tracks, code, ((JsonObject) caption).getString("path"));
                }
            }
        }
        final Object detailCaptions = details == null ? null : details.get("cc");
        if (detailCaptions instanceof JsonArray) {
            for (final Object caption : (JsonArray) detailCaptions) {
                if (caption instanceof JsonObject) {
                    final JsonObject track = (JsonObject) caption;
                    add(tracks, track.getString("language_code"), track.getString("url"));
                }
            }
        }
        return tracks;
    }

    private static void add(final List<SubtitlesStream> tracks, final String originalCode,
                            final String url) {
        if (isNullOrEmpty(originalCode) || isNullOrEmpty(url)) {
            return;
        }
        final boolean generated = originalCode.toLowerCase(Locale.ROOT).endsWith("-auto");
        final String code = generated
                ? originalCode.substring(0, originalCode.length() - 5) : originalCode;
        if (code.isEmpty()) {
            return;
        }
        for (final SubtitlesStream track : tracks) {
            if (url.equals(track.getContent()) && code.equalsIgnoreCase(track.getLanguageTag())
                    && generated == track.isAutoGenerated()) {
                return;
            }
        }
        try {
            tracks.add(new SubtitlesStream.Builder()
                    .setId(originalCode + ".vtt")
                    .setContent(url, true)
                    .setMediaFormat(MediaFormat.VTT)
                    .setLanguageCode(code)
                    .setAutoGenerated(generated)
                    .build());
        } catch (final ParsingException | IllegalArgumentException
                       | IllegalStateException ignored) {
            // One unusable optional caption must not hide the other tracks or prevent playback.
        }
    }
}
